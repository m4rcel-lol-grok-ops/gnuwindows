static void put_pixel(int x, int y, uint32_t color) {
    if ((unsigned)x >= width || (unsigned)y >= height || !fb) return;
    fb[y * pitch32 + x] = color;
}

static void draw_char(int cx, int cy, char ch, uint32_t fg, uint32_t bg) {
    if (ch < 32 || ch > 127) ch = '?';
    const uint8_t *glyph = font8[ch - 32];
    int x0 = cx * 8;
    int y0 = cy * 8;
    for (int row = 0; row < 8; row++) {
        uint8_t bits = glyph[row];
        for (int col = 0; col < 8; col++) {
            uint32_t c = (bits & (0x80 >> col)) ? fg : bg;
            put_pixel(x0 + col, y0 + row, c);
        }
    }
}

static void scroll(void) {
    if (!fb) return;
    uint32_t lines = 8;
    uint32_t row_bytes = pitch32 * sizeof(uint32_t);
    uint8_t *base = (uint8_t *)fb;
    for (uint32_t y = lines; y < height; y++) {
        uint32_t *dst = (uint32_t *)(base + (y - lines) * row_bytes);
        uint32_t *src = (uint32_t *)(base + y * row_bytes);
        for (uint32_t x = 0; x < pitch32; x++)
            dst[x] = src[x];
    }
    for (uint32_t y = height - lines; y < height; y++) {
        uint32_t *dst = (uint32_t *)(base + y * row_bytes);
        for (uint32_t x = 0; x < pitch32; x++)
            dst[x] = 0;
    }
    if (row > 0) row = (int)(height / 8) - 1;
}

void fb_init(GW_BOOT_INFO *bi) {
    active = 0;
    fb = 0;
    if (!bi || !bi->framebuffer_base || bi->framebuffer_width < 80)
        return;
    if (vmm_map_physical_range(bi->framebuffer_base, bi->framebuffer_size) != 0) {
        serial_write("fb: map failed\n");
        return;
    }
    fb = (uint32_t *)(uintptr_t)bi->framebuffer_base;
    width = bi->framebuffer_width;
    height = bi->framebuffer_height;
    pitch32 = bi->framebuffer_pitch ? (bi->framebuffer_pitch / 4) : width;
    bpp = (int)bi->framebuffer_bpp;
    if (bpp != 32 && bpp != 0) {
        /* still try as 32 */
    }
    row = col = 0;
    /* clear */
    for (uint32_t y = 0; y < height; y++)
        for (uint32_t x = 0; x < pitch32; x++)
            fb[y * pitch32 + x] = 0x00101828;
    active = 1;
    serial_write("fb: GOP ");
    serial_write_dec(width);
    serial_putc('x');
    serial_write_dec(height);
    serial_write(" @ ");
    serial_write_hex(bi->framebuffer_base);
    serial_write("\n");
}

int fb_active(void) { return active; }

void fb_putc(char c) {
    if (!active) return;
    int cols = (int)(width / 8);
    int rows = (int)(height / 8);
    if (c == '\n') {
        col = 0;
        row++;
        if (row >= rows) scroll();
        return;
    }
    if (c == '\r') { col = 0; return; }
    if (c == '\b') {
        if (col > 0) {
            col--;
            draw_char(col, row, ' ', 0xFFFFFF, 0x00101828);
        }
        return;
    }
    if (c < 32) return;
    draw_char(col, row, c, 0xE8F0FF, 0x00101828);
    col++;
    if (col >= cols) {
        col = 0;
        row++;
        if (row >= rows) scroll();
    }
}

void fb_write(const char *s) {
    if (!s) return;
    while (*s) fb_putc(*s++);
}
