/*
 * GWKernel ISR stubs - Phase 2
 * Each stub pushes a dummy error code if the CPU does not,
 * then pushes the vector number and jumps to the common handler.
 */

.section .text
.extern isr_common_handler

/* Macro for exceptions that do NOT push an error code */
.macro ISR_NOERR vec
.global isr_stub_\vec
isr_stub_\vec:
    pushq $0                /* dummy error code */
    pushq $\vec             /* vector */
    jmp isr_common
.endm

/* Macro for exceptions that DO push an error code */
.macro ISR_ERR vec
.global isr_stub_\vec
isr_stub_\vec:
    /* error code already on stack */
    pushq $\vec
    jmp isr_common
.endm

